import { createClient, SupabaseClient } from '@supabase/supabase-js';

const STORAGE_KEY_URL = 'marathon_supabase_url';
const STORAGE_KEY_KEY = 'marathon_supabase_anon_key';

// Default project provided by user
export const DEFAULT_SUPABASE_URL = 'https://rtbpanskoryvhmzryurj.supabase.co';
export const DEFAULT_SUPABASE_ANON_KEY = 'sb_publishable__ohRnuXVhKsMoUcgPkE28w_5J-NAAJy';

/**
 * Normalizes Supabase API URL by trimming trailing /rest/v1/ or slashes
 */
export function cleanSupabaseUrl(rawUrl: string): string {
  if (!rawUrl) return '';
  let url = rawUrl.trim();
  url = url.replace(/\/rest\/v1\/?$/i, '');
  url = url.replace(/\/+$/, '');
  return url;
}

// Read from localStorage, env, or user-provided defaults
export function getStoredSupabaseConfig() {
  const envUrl = (import.meta.env.VITE_SUPABASE_URL as string) || '';
  const envKey = (import.meta.env.VITE_SUPABASE_ANON_KEY as string) || '';

  let storedUrl = '';
  let storedKey = '';
  try {
    if (typeof window !== 'undefined') {
      storedUrl = localStorage.getItem(STORAGE_KEY_URL) || '';
      storedKey = localStorage.getItem(STORAGE_KEY_KEY) || '';
    }
  } catch {}

  const resolvedUrl = cleanSupabaseUrl(storedUrl || envUrl || DEFAULT_SUPABASE_URL);
  const resolvedKey = (storedKey || envKey || DEFAULT_SUPABASE_ANON_KEY).trim();

  return {
    url: resolvedUrl,
    anonKey: resolvedKey,
    isConfigured: Boolean(resolvedUrl && resolvedKey),
  };
}

export function saveSupabaseConfig(url: string, anonKey: string) {
  try {
    if (typeof window !== 'undefined') {
      const cleaned = cleanSupabaseUrl(url);
      if (cleaned) localStorage.setItem(STORAGE_KEY_URL, cleaned);
      else localStorage.removeItem(STORAGE_KEY_URL);

      if (anonKey) localStorage.setItem(STORAGE_KEY_KEY, anonKey.trim());
      else localStorage.removeItem(STORAGE_KEY_KEY);
    }
  } catch {}
  // Reset client instance
  supabaseInstance = null;
}

let supabaseInstance: SupabaseClient | null = null;

export function getSupabaseClient(): SupabaseClient | null {
  const config = getStoredSupabaseConfig();
  if (!config.isConfigured) return null;

  if (!supabaseInstance) {
    try {
      supabaseInstance = createClient(config.url, config.anonKey, {
        auth: {
          persistSession: true,
          autoRefreshToken: true,
        },
      });
    } catch (e) {
      console.error('Failed to initialize Supabase client:', e);
      return null;
    }
  }
  return supabaseInstance;
}

